const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const ts = require("typescript");
const moduleValue = { exports: {} };
const code = ts.transpileModule(fs.readFileSync("lib/nrcsRehearsal.ts", "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
vm.runInThisContext(`(function(module,exports){${code}})`)(moduleValue, moduleValue.exports);
const { publicationEligibility, planWebProjection } = moduleValue.exports;
const now = new Date("2026-09-18T05:00:00Z");
const web = { kind: "web", source_id: "output", district_key: "dlpc", payload: { story_id: "story", slug: "existing-story", status: "scheduled", scheduled_at: now.toISOString(), published_at: null } };
assert.equal(publicationEligibility(web, now).visible, true);
assert.equal(publicationEligibility(web, new Date(now.getTime() - 1)).visible, false);
for (const status of ["draft", "unpublished"]) assert.equal(publicationEligibility({ ...web, payload: { ...web.payload, status } }, now).visible, false);
const article = { id: "legacy", district_key: "dlpc", slug: "existing-story", nrcs_output_id: null, nrcs_story_id: null };
assert.equal(planWebProjection(web, [article], now).cmsArticleId, "legacy");
assert.equal(planWebProjection(web, [{ ...article, district_key: "other" }], now).action, "create_new");
assert.equal(planWebProjection(web, [{ ...article, nrcs_output_id: "another" }], now).action, "blocked");
assert.equal(planWebProjection(web, [{ ...article, id: "linked", slug: "old", nrcs_output_id: "output" }, article], now).action, "blocked");
const alert = { kind: "alert", payload: { active: true, start_at: now.toISOString(), end_at: new Date(now.getTime() + 1).toISOString() } };
assert.equal(publicationEligibility(alert, now).visible, true);
assert.equal(publicationEligibility(alert, new Date(now.getTime() + 1)).visible, false);
const homepage = { kind: "homepage", payload: { timezone: "America/Chicago", daily: { publication_date: "2026-09-18" } } };
assert.equal(publicationEligibility(homepage, now).visible, true);
assert.equal(publicationEligibility(homepage, new Date("2026-09-19T05:00:00Z")).visible, false);
assert.equal(publicationEligibility({ ...homepage, payload: { ...homepage.payload, timezone: "America/Los_Angeles" } }, now).visible, false);
console.log("Phase 9 read-only article resolution and schedule/alert/Daily boundary rehearsal checks passed.");
